import { execSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")

const coverage = [
  "seaweedfs/seaweedfs",
  "c9s/bbgo",
  "HelixDB/helix-db",
  "svix/svix-webhooks",
  "seladb/PcapPlusPlus",
  "LadybugDB/ladybug",
  "qdrant/go-client",
  "moonrepo/moon",
  "go-vikunja/vikunja",
  "fosrl/pangolin",
  "fastly/cli",
  "boostsecurityio/poutine",
  "GreptimeTeam/greptimedb",
  "weaviate/weaviate-go-client",
  "upstash/ratelimit-js",
  "tinacms/tinacms",
  "thrasher-corp/gocryptotrader",
  "spacelift-io/terraform-provider-spacelift",
  "rilldata/rill",
  "railwayapp/railpack",
]

const src = readFileSync(join(root, "data/opensource.ts"), "utf8")
const known = new Map()
const blockRe =
  /repo: "([^"]+)",[\s\S]*?detail:\s*\n\s*"([^"]+)"[\s\S]*?prNumber: (\d+),/g
for (const m of src.matchAll(blockRe)) {
  known.set(`${m[1]}#${m[3]}`, m[2].replace(/\s+/g, " ").trim())
}

function lineFromTitle(title) {
  const t = title
    .replace(/^fix(\([^)]+\))?:\s*/i, "")
    .replace(/^feat(\([^)]+\))?:\s*/i, "")
  const s = t.charAt(0).toUpperCase() + t.slice(1)
  return /[.!?]$/.test(s) ? s : `${s}.`
}

const out = {}
for (const repo of coverage) {
  const q = `type:pr+author:Tyagiquamar+is:merged+repo:${encodeURIComponent(repo)}`
  const raw = execSync(`gh api "search/issues?q=${q}&per_page=100"`, {
    encoding: "utf8",
    maxBuffer: 10 * 1024 * 1024,
  })
  const data = JSON.parse(raw)
  const items = (data.items ?? [])
    .map((it) => {
      const pr = it.number
      const key = `${repo}#${pr}`
      const detail = known.get(key) ?? lineFromTitle(it.title)
      const mergedAt = it.closed_at ? it.closed_at.slice(0, 10) : undefined
      return {
        repo,
        title: it.title,
        detail,
        prNumber: pr,
        href: it.html_url,
        mergedAt,
      }
    })
    .sort((a, b) => (b.mergedAt ?? "").localeCompare(a.mergedAt ?? ""))
  out[repo] = items
}

const ts = `import type { RepoPull } from "@/lib/oss-groups"

/** Generated by tools/fetch-oss-repo-pulls.mjs — merged PRs for top coverage repos */
export const ossRepoPulls: Record<string, RepoPull[]> = ${JSON.stringify(out, null, 2)} as Record<string, RepoPull[]>
`

writeFileSync(join(root, "data/oss-repo-pulls.ts"), ts, "utf8")
console.log("wrote data/oss-repo-pulls.ts", Object.values(out).flat().length, "pulls")
